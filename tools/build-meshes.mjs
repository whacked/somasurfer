/**
 * Turn the pinned brainproject brain.glb into the project's own mesh files.
 *
 *   (cd tools/mesh-build && npm ci)        # once: the build-only decoder and simplifier
 *   node tools/build-meshes.mjs --source <dir>
 *
 * `<dir>` holds `brain.glb` and `manifest.json` from brainproject at the commit
 * pinned in packages/atlas-assets/attribution.json (`brainproject-brain-glb`).
 * Both are checked against the pinned SHA-256 before anything is read; a file
 * that does not match is refused, not built from. They are NOT in the
 * repository: 4.9 MB of third-party mesh, reduced here to the committed files.
 *
 * Writes:
 *   packages/atlas-assets/brain/zanatomy-<sha7>/meshes.lowres.bin    low tier, cleared group
 *   packages/atlas-assets/brain/zanatomy-<sha7>/meshes.fullres.bin   full tier, cleared group
 *   packages/atlas-assets/brain/zanatomy-<sha7>/structures.json      what is in them, and what is not
 *   packages/atlas-assets/provenance/brain-zanatomy-<sha7>.json      structure → material → source, all 437
 *
 * It does not decide whether the result is acceptable. tools/check-mesh-assets.mjs
 * does, from the committed files alone, and re-measures every figure this
 * writes rather than trusting it.
 */

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { join } from 'node:path';
import { REPO_ROOT, fail, rel } from './lib/repo.mjs';
import { decodeGlbNodes } from './lib/glb.mjs';
import { GROUPS, buildProvenance } from './lib/brain-provenance.mjs';
import { buildTiers } from './lib/brain-meshes.mjs';
import { BRAIN_MESH_BUILD, brainAssetPaths } from './lib/brain-asset-paths.mjs';

const args = process.argv.slice(2);
const sourceAt = args.indexOf('--source');
const source = sourceAt >= 0 ? args[sourceAt + 1] : process.env.ATLAS_BRAINPROJECT_DIR;
if (!source) fail('build-meshes', ['Pass --source <dir> holding brain.glb and manifest.json (or set ATLAS_BRAINPROJECT_DIR).']);

const attribution = JSON.parse(readFileSync(join(REPO_ROOT, 'packages', 'atlas-assets', 'attribution.json'), 'utf8'));
const pin = attribution.upstreamSources.find((s) => s.id === 'brainproject-brain-glb')?.pinned;
if (!pin) fail('build-meshes', ['attribution.json has no pinned `brainproject-brain-glb` source.']);

const inputs = {};
for (const [name, key] of [['brain.glb', 'brain-atlas/models/brain.glb'], ['manifest.json', 'brain-atlas/models/manifest.json']]) {
  const p = join(source, name);
  if (!existsSync(p)) fail('build-meshes', [`${p} does not exist.`]);
  const bytes = readFileSync(p);
  const sha = createHash('sha256').update(bytes).digest('hex');
  if (sha !== pin.files[key].sha256) {
    fail('build-meshes', [
      `${p} has SHA-256 ${sha}.`,
      `The pin (attribution.json, brainproject ${pin.commit.slice(0, 7)}) is ${pin.files[key].sha256}.`,
      'This is not the file the licence memo verified. Fetch the pinned commit, or re-verify and re-pin.',
    ]);
  }
  inputs[name] = bytes;
}

const paths = brainAssetPaths(pin.commit);
const { nodes } = await decodeGlbNodes(inputs['brain.glb']);
const manifest = JSON.parse(inputs['manifest.json'].toString('utf8'));
const manifestById = new Map(manifest.nodes.map((n) => [n.id, n]));
const provenance = buildProvenance(nodes);

const cleared = provenance.structures.filter((s) => s.group === GROUPS.cleared);
const tiers = await buildTiers({ nodes, structures: cleared, ...BRAIN_MESH_BUILD });
const reportById = new Map(tiers.report.map((r) => [r.id, r]));

const sha256 = (b) => createHash('sha256').update(b).digest('hex');
const gz = (b) => gzipSync(b, { level: 9 }).length;

const structuresDoc = {
  schema: 'atlas-brain-structures/1',
  id: paths.id,
  comment: [
    'Generated by tools/build-meshes.mjs. Do not edit; rebuild.',
    'Every structure listed under `structures` is in both mesh files, as the same table slot.',
    'Positions are in the source mesh frame: glTF, metres, +x = the model\'s left, +y = superior,',
    '+z = anterior. It is NOT MNI space; packages/atlas-assets/registration/ maps MNI mm to it.',
  ],
  source: {
    upstream: 'brainproject-brain-glb',
    commit: pin.commit,
    files: { 'brain.glb': pin.files['brain-atlas/models/brain.glb'].sha256, 'manifest.json': pin.files['brain-atlas/models/manifest.json'].sha256 },
  },
  frame: {
    space: 'brainproject mesh world (glTF export of the Z-Anatomy Blender scene)',
    units: 'metre',
    axes: { x: 'model left', y: 'superior', z: 'anterior' },
    quantisation: { origin: tiers.frame.origin, step: tiers.frame.step, quantisationStepMm: Math.max(...tiers.frame.step) * 1000 },
  },
  build: {
    ...BRAIN_MESH_BUILD,
    simplifier: 'meshoptimizer 1.3.0 simplify(), LockBorder; topology-preserving edge collapse',
    errorMeasure: 'symmetric Hausdorff and mean surface distance between the low and full tiers, every vertex, exact nearest-surface; millimetres in the mesh frame',
  },
  tiers: {
    low: { file: paths.lowFile, bytes: tiers.low.length, gzipBytes: gz(tiers.low), sha256: sha256(tiers.low), loading: 'eager' },
    full: { file: paths.fullFile, bytes: tiers.full.length, gzipBytes: gz(tiers.full), sha256: sha256(tiers.full), loading: 'lazy' },
  },
  counts: { structures: cleared.length, excluded: provenance.structures.length - cleared.length, ...provenance.counts },
  structures: cleared.map((s, slot) => {
    const r = reportById.get(s.id);
    const m = manifestById.get(s.id);
    return {
      id: s.id,
      slot,
      name: s.name.trim(),
      label: s.label,
      category: s.category,
      side: s.side,
      region: m?.region ?? null,
      ta2: m?.ta2 ?? [],
      sources: s.sources,
      basis: s.basis,
      full: { triangles: r.full.triangles, vertices: r.full.vertices, areaMm2: round(r.full.areaMm2, 1) },
      low: { triangles: r.low.triangles, vertices: r.low.vertices, areaMm2: round(r.low.areaMm2, 1) },
      sourceTriangles: r.sourceTriangles,
      errorMm: { hausdorff: round(r.hausdorffMm, 3), mean: round(r.meanDeviationMm, 3) },
    };
  }),
  excluded: provenance.structures
    .filter((s) => s.group !== GROUPS.cleared)
    .map((s) => ({ id: s.id, name: s.name.trim(), category: s.category, side: s.side, group: s.group, heldBecause: s.heldBecause })),
};

function round(x, d) {
  const k = 10 ** d;
  return Math.round(x * k) / k;
}

const provenanceDoc = {
  schema: 'atlas-brain-provenance/1',
  comment: [
    'Generated by tools/build-meshes.mjs from the pinned brain.glb under docs/asset-licensing.md 7.3.',
    'Not hand-written, and not shipped: the licence gate (rule 10) reads it to check what each',
    'brain mesh file actually contains against what its attribution entry cites.',
  ],
  source: structuresDoc.source,
  counts: { ...provenance.counts, cortical: provenance.cortical, corticalHeld: provenance.corticalHeld },
  structures: provenance.structures,
};

mkdirSync(join(REPO_ROOT, paths.dir), { recursive: true });
mkdirSync(join(REPO_ROOT, 'packages', 'atlas-assets', 'provenance'), { recursive: true });
writeFileSync(join(REPO_ROOT, paths.dir, 'meshes.lowres.bin'), tiers.low);
writeFileSync(join(REPO_ROOT, paths.dir, 'meshes.fullres.bin'), tiers.full);
writeFileSync(join(REPO_ROOT, paths.dir, 'structures.json'), `${JSON.stringify(structuresDoc, null, 1)}\n`);
writeFileSync(join(REPO_ROOT, paths.provenance), `${JSON.stringify(provenanceDoc, null, 1)}\n`);

const errs = structuresDoc.structures.map((s) => s.errorMm.hausdorff).sort((a, b) => a - b);
console.log([
  `brain meshes ${paths.id}`,
  `  provenance: ${Object.entries(provenance.counts).map(([k, v]) => `${k} ${v}`).join(', ')}; cortical held ${provenance.corticalHeld} of ${provenance.cortical}`,
  `  low tier  ${structuresDoc.tiers.low.bytes} B, gzip ${structuresDoc.tiers.low.gzipBytes} B`,
  `  full tier ${structuresDoc.tiers.full.bytes} B, gzip ${structuresDoc.tiers.full.gzipBytes} B`,
  `  Hausdorff low↔full: median ${errs[errs.length >> 1]} mm, max ${errs.at(-1)} mm over ${errs.length} structures`,
  `  wrote ${rel(join(REPO_ROOT, paths.dir))}/ and ${paths.provenance}`,
].join('\n'));
