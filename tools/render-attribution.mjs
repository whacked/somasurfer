/**
 * Renders packages/atlas-assets/ATTRIBUTION.md from attribution.json.
 *
 * attribution.json is the authority; the Markdown is a view of it. Both are
 * committed, and the drift gate (tools/check-audit-drift.mjs) keeps them
 * byte-identical, for the same reason it does for the admissibility report: a
 * human-readable attribution file that has fallen behind the machine-readable
 * one is worse than not having it.
 *
 * Writes to stdout. `npm run attribution:report` redirects it.
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT } from './lib/repo.mjs';

const ASSETS = join(REPO_ROOT, 'packages', 'atlas-assets');
const data = JSON.parse(readFileSync(join(ASSETS, 'attribution.json'), 'utf8'));

const out = [];
const line = (s = '') => out.push(s);

line('# Atlas asset attribution');
line();
line('Generated from `packages/atlas-assets/attribution.json` by');
line('`tools/render-attribution.mjs`. Do not edit this file; edit the JSON and');
line('run `npm run attribution:report` in `packages/atlas-assets`.');
line();
line('Every file shipped from this package appears below with its licence, its');
line('copyright holder and where it came from. The build renders this list into');
line('the site, so an asset cannot reach a user without its attribution.');
line();

if (data.packageLicenceStatus === 'pending') {
  line(`> **Package licence: pending.** Settled by ${data.packageLicenceDecision}. Until then this`);
  line('> package carries first-party assets only, and the entries below say so.');
  line();
}

line('## Assets');
line();
line('| asset | files | licence | holder | share-alike |');
line('| --- | --- | --- | --- | --- |');
for (const e of data.entries) {
  const licence = e.licenceUrl ? `[${e.licence}](${e.licenceUrl})` : e.licence;
  line(`| ${e.title} | ${e.files.map((f) => `\`${f}\``).join('<br>')} | ${licence} | ${e.holder} | ${e.shareAlike ? '**yes**' : 'no'} |`);
}
line();

line('## Provenance');
line();
for (const e of data.entries) {
  line(`### ${e.title}`);
  line();
  line(`- **id** \`${e.id}\``);
  line(`- **licence** ${e.licence}`);
  line(`- **holder** ${e.holder}`);
  line(`- **source** ${e.source}`);
  if (e.note) line(`- **note** ${e.note}`);
  line();
}

const shareAlike = data.entries.filter((e) => e.shareAlike);
line('## Share-alike obligations');
line();
if (shareAlike.length === 0) {
  line('None. No asset in this package currently carries a share-alike licence.');
  line();
  line('The separation mechanism is in place regardless, because it has to exist');
  line('before the first such asset arrives, not after:');
} else {
  line('The following assets carry a share-alike obligation:');
  line();
  for (const e of shareAlike) line(`- ${e.title} — ${e.licence}`);
  line();
  line('That obligation is confined to this package by the following, checked on');
  line('every push by `tools/check-licence-separation.mjs`:');
}
line();
line('1. No code package declares a dependency on `@gstack/atlas-assets`.');
line('2. No code package imports from it.');
line('3. The asset package is outside the npm workspace list, so it is never');
line('   linked into `node_modules` where an import could resolve by accident.');
line('4. No asset bytes are embedded in the shipped JavaScript or CSS bundle.');
line('   Assets are emitted as separate files under `dist/assets/`, which');
line('   carries this file and the asset `LICENSE` alongside them.');
line();
line('See `packages/atlas-assets/LICENSE` and the repository-root `LICENSE`.');

process.stdout.write(out.join('\n') + '\n');
