/**
 * Generates docs/alc-1-body-template-audit.md on stdout.
 *
 * Every number in that document is computed here, from committed inputs only:
 * the shipped templates, the naming layer, and ci/bd-centreline-trials.json.
 * No mesh data, so CI can regenerate it and compare byte for byte
 * (tools/check-audit-drift.mjs). A report about a template that has fallen
 * behind the template is worse than no report.
 *
 * Determinism matters more than it looks. `acceptBodyTemplate` is seeded, so
 * the probe is reproducible; nothing here reads a clock, a directory listing
 * order, or an environment variable. If this file ever needs a timestamp, the
 * drift gate is the thing that will object, and it will be right.
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT } from './lib/repo.mjs';

const ASSETS = join(REPO_ROOT, 'packages', 'atlas-assets');
const read = (...p) => JSON.parse(readFileSync(join(...p), 'utf8'));

const body = read(ASSETS, 'templates', 'bp3d-4.0-adult-body-centroid.body.json');
const brain = read(ASSETS, 'templates', 'icbm152-2009c-asym.brain-volume.json');
const names = read(ASSETS, 'labels', 'names.json');
const coverings = read(ASSETS, 'labels', 'coverings.json');
const trials = read(REPO_ROOT, 'ci', 'bd-centreline-trials.json');

const { acceptBodyTemplate, formatLevelTable } = await import('../packages/alc/src/testing/templateAcceptance.ts');

const KNOTS = body.slabs[0].surfaceRadiiMm.length;
const report = acceptBodyTemplate(body, { consistencyAzimuths: KNOTS * 10 });

const out = [];
const line = (s = '') => out.push(s);
const fixed = (v, n = 2) => (Number.isFinite(v) ? v.toFixed(n) : '∞');

// ---------------------------------------------------------------------------

line('# ALC-1 real body template audit — measured report');
line();
line('Generated by `tools/report-template-audit.mjs` from the committed templates,');
line('the naming layer and `ci/bd-centreline-trials.json`. Every number below is');
line('computed; `tools/check-audit-drift.mjs` fails if this file and the generator');
line('disagree. Regenerate with:');
line();
line('```');
line('cd packages/atlas-assets && npm run templates:audit');
line('```');
line();
line('This is the companion to `docs/alc-1-admissibility.md`, which measures the');
line('*clinically parameterised* templates. This one measures the template actually');
line('derived from the mesh set, which is the one that ships.');
line();

// --- 1. the verdict --------------------------------------------------------

line('## 1. The verdict');
line();
line(`Template \`${body.id}\`, ${body.slabs.length} levels, ${KNOTS} azimuth knots per level.`);
line();
line(`**${report.accepted ? 'ACCEPTED' : 'REJECTED'}.**`);
line();
line('| stage | role | result |');
line('| --- | --- | --- |');
const stageRole = {
  STRUCTURE: 'preconditions',
  AUDIT: '**localiser, not the gate**',
  PROBE: 'interior probe',
  'ADMISSIBILITY-CONSISTENCY': '**the gate**',
};
for (const stage of report.stages) {
  const measured = Object.entries(stage.measurements).map(([k, v]) => `${k}=${v}`).join(', ');
  line(`| \`${stage.stage}\` | ${stageRole[stage.stage] ?? ''} | ${stage.passed ? 'pass' : '**FAIL**'} — ${measured} |`);
}
line();
if (!report.accepted) {
  line('Every problem, verbatim:');
  line();
  for (const stage of report.stages) {
    for (const p of stage.problems) line(`- \`${stage.stage}\` — ${p}`);
  }
  line();
}
line('`scanBodyTemplateFolds` is the gate and `auditBodyTemplate` is not. The');
line('per-level audit asks only whether a level violates its own two bisector');
line('planes, which 162 of 3 228 templates across the parameter box satisfy while');
line('still folding — a distant level can claim the point on the convex side of a');
line('curve. The audit is reported here because its per-level margins are the right');
line('tool for *localising* a fold, and for no other reason.');
line();

// --- 2. unverified ---------------------------------------------------------

const unverified = body.provenance?.measurement?.unverified ?? [];
line('## 2. Regions the scan could not measure');
line();
if (unverified.length === 0) {
  const rays = body.slabs.length * KNOTS;
  line(`**None.** All ${rays} rays — ${body.slabs.length} levels x ${KNOTS} azimuths — reached the skin`);
  line('mesh, so no azimuth is carrying a one-sided bound and every radius above is a');
  line('measurement rather than an upper estimate.');
  line();
  line('If a ray ever fails, the pipeline fills that azimuth with the largest radius');
  line('measured at the level — an **upper** bound — records it here as `UNVERIFIED`,');
  line('and the template is then sound *under that bound*, which is a weaker claim and');
  line('is published as one. The direction is the point: utilisation rises with radius,');
  line('so over-estimating makes the fold test strictly harder to pass. Filling with a');
  line("neighbour's radius, or with the level's minimum, would make an unmeasurable");
  line('region read green.');
} else {
  line(`**${unverified.length} azimuth(s) UNVERIFIED.** Each is filled with an upper bound on the`);
  line('radius, so the gate result below is soundness *under a one-sided bound* rather');
  line('than measured soundness.');
  line();
  line('| level | azimuth turns | clock | bound mm | direction | reason |');
  line('| --- | --- | --- | --- | --- | --- |');
  for (const u of unverified) {
    line(`| \`${u.level}\` | ${u.azimuthTurns} | ${u.clock} | ${u.boundMm} | ${u.boundDirection} | ${u.reason} |`);
  }
}
line();

// --- 3. per-level table ----------------------------------------------------

line('## 3. Per level');
line();
line('`docs/alc-1-admissibility.md` §5 requires this table to ship with any real');
line('template. Fold radius is where the level\'s own two bisector planes meet;');
line('utilisation is body radius over fold radius; margin is the difference.');
line();
line(formatLevelTable(report));
line();

// --- 4. declarations -------------------------------------------------------

const declarations = body.provenance?.measurement?.declarations ?? [];
line('## 4. Declared representation limits');
line();
line('Things this template is honest about and a consumer can still be misled by,');
line('because the gate passes and nothing in the geometry is wrong. Each one is a');
line('field in `provenance.measurement.declarations[]` so a consumer can branch on');
line('it rather than read it here.');
line();
if (declarations.length === 0) {
  line('None declared.');
} else {
  line('| id | severity | affects | sound and complete? |');
  line('| --- | --- | --- | --- |');
  for (const d of declarations) {
    const complete = d.completeness.startsWith('SOUND, NOT COMPLETE')
      ? 'sound, **not complete**'
      : (d.completeness.startsWith('Exact') ? 'exact' : d.completeness.split('.')[0]);
    line(`| \`${d.id}\` | ${d.severity} | ${d.affects.map((l) => `\`${l}\``).join(', ')} | ${complete} |`);
  }
  line();
  for (const d of declarations) {
    line(`### \`${d.id}\``);
    line();
    line(d.summary);
    line();
    line(`- **why** ${d.why}`);
    line(`- **how it is detected** ${d.detection}`);
    line(`- **completeness** ${d.completeness}`);
    line(`- **what would remove it** ${d.fix}`);
    line();
    if (d.id === 'surface-is-limb') {
      line('| level | clock sectors | witness bone | radius range mm |');
      line('| --- | --- | --- | --- |');
      for (const r of d.perLevel) {
        line(`| \`${r.level}\` | ${r.clock.join(', ')} | ${r.bones.join(', ')} | ${r.radiusRangeMm.join(' – ')} |`);
      }
      line();
    } else if (d.id === 'single-sacral-level') {
      const r = d.perLevel[0];
      line(`| level | height mm | median level height mm | ratio | axial cell at ${body.maxUsefulDigits} digits mm |`);
      line('| --- | --- | --- | --- | --- |');
      line(`| \`${r.level}\` | ${r.heightMm} | ${r.medianLevelHeightMm} | ${r.ratio}x | ${r.axialCellMm} |`);
      line();
    }
  }
}

// --- 5. the centreline trials ---------------------------------------------

line('## 5. How the centreline rule was chosen');
line();
line('Four candidates, all built from the same mesh set and all put through the same');
line('gate. The three that lost are published rather than deleted: a construction');
line('that was chosen rather than guessed is only demonstrable if the alternatives\'');
line('numbers are on the record.');
line();
line('| candidate | ships | verdict | worst level | worst utilisation | folded / probed | round trip | L5/S1 kink |');
line('| --- | --- | --- | --- | --- | --- | --- | --- |');
for (const t of trials.trials) {
  line(
    `| \`${t.id}\` | ${t.ships ? '**yes**' : 'no'} | ${t.accepted ? 'ACCEPTED' : '**REJECTED**'}`
    + ` | \`${t.audit.worstLevel}\` | ${fixed(t.audit.worstUtilisation, 3)}`
    + ` | ${t.scan.foldedPoints} / ${t.scan.probed}`
    + ` | ${t.probe.failures} / ${t.probe.samples}`
    + ` | ${t.lumbosacral.kinkDeg}° |`,
  );
}
line();
for (const t of trials.trials) {
  line(`- \`${t.id}\` — ${t.why}`);
}
line();
line('Published violations, for the candidates that folded. A published violation is');
line('a result; a quietly-passing template is not.');
line();
const violating = trials.trials.filter((t) => t.audit.violations.length > 0);
if (violating.length === 0) {
  line('None — no candidate had a per-level violation to localise.');
} else {
  line('| candidate | level | azimuth turns | fold radius mm | body radius mm | margin mm | utilisation |');
  line('| --- | --- | --- | --- | --- | --- | --- |');
  for (const t of violating) {
    for (const v of t.audit.violations) {
      line(
        `| \`${t.id}\` | \`${v.level}\` | ${v.azimuthTurns} | ${fixed(v.foldRadiusMm, 1)}`
        + ` | ${fixed(v.bodyRadiusMm, 1)} | **${fixed(v.marginMm, 1)}** | ${fixed(v.utilisation, 3)} |`,
      );
    }
  }
}
line();
line('Note which column is doing the work. On the rejected candidates the per-level');
line('audit *and* the scan both fire, but the scan finds more levels folding than the');
line('audit condemns — the audit is a necessary condition, not a sufficient one, and');
line('that is why the scan is the gate.');
line();

// --- 6. the sacral endplate -----------------------------------------------

const sacral = body.provenance.measurement.levels.find((l) => l.level === 'S01');
line('## 6. The upper sacral endplate');
line();
line('`docs/alc-1-admissibility.md` §5 requirement 2: `S01`\'s axis follows the upper');
line('sacral endplate, not the sacrum\'s chord. Measured on the mesh:');
line();
line('| quantity | value |');
line('| --- | --- |');
line(`| endplate centre, template mm | ${JSON.stringify(sacral.endplateMm)} |`);
line(`| endplate normal | ${JSON.stringify(sacral.endplateNormal)} |`);
line(`| endplate slope from horizontal | ${sacral.endplateSlopeDeg}° |`);
line(`| planarity ratio (middle variance / least variance) | ${sacral.endplatePlanarityRatio} |`);
line(`| triangles in the endplate band | ${sacral.endplateBandTriangles} |`);
line(`| band area | ${sacral.endplateBandAreaMm2} mm² |`);
line(`| axis rule | \`${sacral.axialRule}\` |`);
line(`| resulting kink at the L5/S1 boundary | **${sacral.kinkAtCranialBoundaryDeg}°** |`);
line();
line('The planarity ratio is why the least-variance plane fit is trustworthy here: the');
line('endplate is a shallow dome tens of millimetres across, so its normal is the');
line('least-variance direction by a wide margin rather than by a whisker.');
line();

// --- 7. kinks --------------------------------------------------------------

line('## 7. Tangent turn per boundary');
line();
line('The fold radius is inversely proportional to the tangent turn at a level');
line('boundary, so this is the first table to read when a level folds. One degree');
line('over a 30 mm level is a fold radius near 1 700 mm; thirty degrees is near');
line('57 mm.');
line();
line('| level | height mm | kink at cranial boundary | centroid off axis mm | azimuths measured |');
line('| --- | --- | --- | --- | --- |');
for (const l of body.provenance.measurement.levels) {
  line(
    `| \`${l.level}\` | ${l.heightMm} | ${l.kinkAtCranialBoundaryDeg === null ? '—' : `${l.kinkAtCranialBoundaryDeg}°`}`
    + ` | ${l.centroidOffAxisMm} | ${l.azimuthsMeasured} / ${l.azimuthsMeasured + l.azimuthsUnverified} |`,
  );
}
line();

// --- 8. precision ----------------------------------------------------------

const p = body.provenance.measurement.precision;
line('## 8. Precision, derived rather than chosen');
line();
line(`\`maxUsefulDigits\` is **${body.maxUsefulDigits}**, and the \`BD\` frame itself caps at ${p.frameCap}.`);
line();
line(`Rule: ${p.rule}.`);
line();
line('| quantity | value |');
line('| --- | --- |');
for (const [k, v] of Object.entries(p.basis)) line(`| ${k} | ${v} |`);
line();
line('This is a property of the **source mesh**, not of the frame. The 99%-reduced');
line('OBJ set has a 6.25 mm mean edge, and one octree digit past that the address');
line('claims a distinction the geometry cannot make. A finer source raises this');
line('number without invalidating any address already issued, because truncating an');
line('address is always valid and the cells only ever subdivide.');
line();
line('Consumers must take the boundary from the **bound template\'s** own');
line('`maxUsefulDigits` rather than from a literal. `locate()` raises');
line('`flags.overPrecise` relative to whichever template is bound, so a harness that');
line('hard-codes a digit count is pinned to one template and inverts against another.');
line();

// --- 9. BV -----------------------------------------------------------------

line('## 9. The `BV` brain-volume template');
line();
line(`Template \`${brain.id}\`, from ${brain.provenance.source.dataset}.`);
line();
line('| quantity | value |');
line('| --- | --- |');
line(`| declared world space | \`${brain.provenance.header.declaredSpace}\` (\`sform_code\` ${brain.provenance.header.sformCode}) |`);
line(`| voxel grid | ${brain.provenance.header.dim.join(' x ')} at ${brain.provenance.header.pixdimMm.join(' x ')} mm |`);
line(`| brain mask voxels | ${brain.provenance.measurement.brainMaskVoxels} |`);
const bb = brain.provenance.measurement.brainBoxMm;
const ib = brain.provenance.measurement.imageBoxMm;
line(`| brain bounding box, mm | x ${bb.x.join(' … ')}, y ${bb.y.join(' … ')}, z ${bb.z.join(' … ')} |`);
line(`| image field of view, mm | x ${ib.x.join(' … ')}, y ${ib.y.join(' … ')}, z ${ib.z.join(' … ')} |`);
line(`| extents from the AC, mm | L ${brain.extents.left}, R ${brain.extents.right}, A ${brain.extents.anterior}, P ${brain.extents.posterior}, S ${brain.extents.superior}, I ${brain.extents.inferior} |`);
line(`| \`maxUsefulDigits\` | ${brain.maxUsefulDigits} |`);
line();
line('The frame normalises against the **brain mask**, not the field of view. The');
line('field of view includes skull, scalp and a stub of neck; both boxes are');
line('published so the difference is visible rather than implied.');
line();
line('### AC–PC landmarks');
line();
line('| landmark | status | value | basis |');
line('| --- | --- | --- | --- |');
for (const [name, lm] of Object.entries(brain.provenance.landmarks)) {
  const value = lm.mm ? JSON.stringify(lm.mm) : (lm.directionMm ? JSON.stringify(lm.directionMm) : '`null`');
  line(`| \`${name}\` | **${lm.status}** | ${value} | ${lm.basis} |`);
}
line();
line('The PC distance is `null` and that is deliberate. The distribution ships images');
line('and masks, not landmark coordinates, and locating the posterior commissure in an');
line('image is a segmentation problem rather than a header read. **No field of this');
line('template is a function of that distance** — the frame takes the AC as its origin');
line('and the AC–PC line as its anterior axis, and both of those are measured. A');
line('plausible value would be the only unmeasured number in the file, and');
line('`tools/verify-asset-templates.mjs` fails if an `UNVERIFIED` landmark ever');
line('acquires one.');
line();

// --- 10. naming layer ------------------------------------------------------

line('## 10. The naming layer');
line();
line(`Index version \`${names.version}\`, stamped into every \`resolve()\` result.`);
line();
const totals = coverings.provenance.totals;
line('| quantity | value |');
line('| --- | --- |');
line(`| structures | ${names.structureCount} |`);
line(`| cells | ${totals.cells} at ${coverings.digits} refinement digit(s) |`);
line(`| interior samples | ${totals.samples} |`);
line(`| with an UBERON cross-reference | ${names.structures.filter((s) => s.uberon.length > 0).length} |`);
line(`| interior test | ${coverings.provenance.interiorTest} |`);
line(`| ambiguous interior tests | ${totals.ambiguousInteriorTests} |`);
line();
const surfaceOnly = coverings.provenance.perStructure.filter((s) => s.coverage === 'surface');
line('### Coverings that are not solid');
line();
if (surfaceOnly.length === 0) {
  line('None. Every structure resolved as a solid.');
} else {
  line('A structure whose interior the ray-parity test could not resolve falls back to a');
  line('**surface** covering and says so. For a structure thinner than a cell the two');
  line('are the same set; for anything else the flag is the warning.');
  line();
  line('| structure | name | element meshes | samples | cells |');
  line('| --- | --- | --- | --- | --- |');
  for (const s of surfaceOnly) {
    line(`| \`${s.id}\` | ${s.name} | ${s.parts} | ${s.samples} | ${s.cells} |`);
  }
}
line();
line('### Structures the `BD` frame does not wholly reach');
line();
const partial = coverings.provenance.perStructure
  .filter((s) => s.clampedPoints > 0)
  .sort((a, b) => a.inFrameFraction - b.inFrameFraction);
if (partial.length === 0) {
  line('None.');
} else {
  line('A point `encodeBody` had to clamp is **not** a cell of the structure: it would');
  line('assert that whatever lies past the end of the column is the last level. Those');
  line('points are dropped and the fraction that remained is published.');
  line();
  line('| structure | name | in frame | dropped | why |');
  line('| --- | --- | --- | --- | --- |');
  for (const s of partial) {
    line(
      `| \`${s.id}\` | ${s.name} | ${(s.inFrameFraction * 100).toFixed(1)}% `
      + `| ${s.clampedPoints} / ${s.samples} | ${s.notes.join('; ')} |`,
    );
  }
  line();
  line('The brain is **absent from this index entirely** for the same reason taken to');
  line('its limit: 0.2% of it falls inside `BD`, because it sits above `C01`. It is a');
  line('`BV` structure, and `BV` ships coordinates without names until a brain');
  line('parcellation licence is cleared — see `docs/asset-licensing.md`.');
}
line();

// --- 11. provenance --------------------------------------------------------

line('## 11. Provenance and the axis convention');
line();
line('| source | value |');
line('| --- | --- |');
line(`| body mesh set | ${body.provenance.source.dataset} ${body.provenance.source.release}, ${body.provenance.source.variant} |`);
line(`| body mesh holder | ${body.provenance.source.holder} |`);
line(`| brain template | ${brain.provenance.source.dataset} |`);
line(`| brain template holder | ${brain.provenance.source.holder} |`);
line(`| ontology | UBERON ${names.provenance.uberon?.dataVersion ?? '(none)'} |`);
line(`| template space | ${body.provenance.frame.space} |`);
line();
line('The axis convention is **re-derived from the mesh set on every build**, not');
line('trusted to a comment, because a left–right flipped atlas passes every fold');
line('gate, every round trip and every conformance test and is only wrong about the');
line('patient. The witnesses are viscera whose side is not in question:');
line();
line('| witness | FMA | expected | observed | mean x mm |');
line('| --- | --- | --- | --- | --- |');
for (const w of body.provenance.frame.laterality) {
  line(`| ${w.witness} | \`${w.fma}\` | ${w.expected} | ${w.observed} | ${w.meanXMm} |`);
}
line();
line('Licensing, including the upstream discrepancy the pipeline holds the');
line('conservative side of, is in `docs/asset-licensing.md`.');

process.stdout.write(`${out.join('\n')}\n`);
